// Writes lib/core/search/search_fold.g.dart: every character of the Basic
// Multilingual Plane whose canonical decomposition (NFD) carries combining
// marks, mapped to what is left once they are dropped.
//
// The web normalizes search text with `text.normalize('NFD')` and strips
// `\p{M}` (src/core/lib/search.ts). Dart has no Unicode normalization, so the
// app folds precomposed characters through this table instead, built from the
// same JavaScript `normalize` the web runs. Run it from mobile/ after a Node
// upgrade that brings a new Unicode version:
//
//   node tool/build_search_fold.mjs

import { writeFileSync } from 'node:fs';

const mark = /\p{M}/u;
const entries = [];

for (let cp = 0; cp < 0x10000; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;

  const char = String.fromCharCode(cp);
  const decomposed = char.normalize('NFD');

  if (decomposed === char || ![...decomposed].some(c => mark.test(c))) {
    continue;
  }

  entries.push([cp, decomposed.replace(/\p{M}/gu, '')]);
}

const hex = cp => `0x${cp.toString(16).toUpperCase().padStart(4, '0')}`;
// Printable ASCII as is, the rest escaped so the file stays plain ASCII.
const escape = text =>
  [...text]
    .map(c =>
      /^[A-Za-z0-9 ]$/.test(c)
        ? c
        : `\\u{${c.codePointAt(0).toString(16).toUpperCase()}}`,
    )
    .join('');

const lines = entries.map(([cp, folded]) => `  ${hex(cp)}: '${escape(folded)}',`);

writeFileSync(
  new URL('../lib/core/search/search_fold.g.dart', import.meta.url),
  `// GENERATED by tool/build_search_fold.mjs from JavaScript's normalize('NFD').
// Do not edit by hand.

/// Precomposed characters and what is left of them once their combining marks
/// are dropped (\`é\` → \`e\`, \`Ǖ\` → \`U\`): the app's stand-in for the web's
/// \`normalize('NFD')\` followed by removing \`\\p{M}\`.
const searchFold = <int, String>{
${lines.join('\n')}
};
`,
);

console.log(`${entries.length} characters written`);
